import assert from "node:assert/strict";
import { chromium } from "playwright";
import { readFile } from "node:fs/promises";
const base = process.argv[2] || "http://127.0.0.1:8787";
const fixture = JSON.parse(await readFile(new URL("./fixtures/bundle/runs/orx-synthetic-v1/sessions/2026-07-30.json", import.meta.url)));
const equity = JSON.parse(await readFile(new URL("./fixtures/bundle/runs/orx-synthetic-v1/equity.json", import.meta.url)));
const browser = await chromium.launch();
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  await page.goto(base + "/styleguide/");
  const preview = page.locator('.theme-preview[data-theme="light"]');
  const candles = preview.locator('[data-chart="candles"]');
  await candles.scrollIntoViewIfNeeded();
  await candles.locator("svg .candle").first().waitFor();
  assert.equal(await candles.locator("svg .candle").count(), 78);
  assert.equal(await candles.locator("tbody tr").count(), 78);
  await candles.screenshot({ path: "test/artifacts/chart-candles.png", animations: "disabled" });
  const point = candles.locator(".candle").first();
  await point.focus();
  assert.match(await page.locator(".tooltip").textContent(), /20,000/);
  await page.keyboard.press("ArrowRight");
  assert.equal(await candles.locator(".candle").nth(1).evaluate((el) => document.activeElement === el), true);
  assert.match(await page.locator(".tooltip").textContent(), /20,005.25/);
  const curve = preview.locator('[data-chart="equity"]');
  await curve.scrollIntoViewIfNeeded();
  await curve.locator("svg").waitFor();
  assert.ok((await curve.textContent()).includes("25.4"));
  assert.ok((await curve.textContent()).includes("Holdout starts"));
  await curve.screenshot({ path: "test/artifacts/chart-equity.png", animations: "disabled" });
  const underwater = preview.locator('[data-chart="drawdown"]');
  await underwater.scrollIntoViewIfNeeded();
  await underwater.locator("svg").waitFor();
  assert.ok((await underwater.textContent()).includes("-43.44"));
  await underwater.screenshot({ path: "test/artifacts/chart-drawdown.png", animations: "disabled" });
  const dense = preview.locator('[data-chart="dense"]');
  await dense.scrollIntoViewIfNeeded();
  await dense.locator("canvas").waitFor();
  assert.equal(await dense.locator("tbody tr").count(), 320);
  await dense.locator("canvas").focus();
  await page.keyboard.press("End");
  assert.match(await dense.locator("canvas").getAttribute("aria-label"), /volume/);
  const result = await page.evaluate(async ({ session, equity }) => {
    const core = await import("/assets/charts/core.js");
    const candle = await import("/assets/charts/candles.js");
    const curve = await import("/assets/charts/equity.js");
    const host = document.createElement("div"); host.style.width = "1000px"; document.body.append(host);
    const opts = { meta: { run_id: "test", source: "Synthetic", sample: "In sample" }, title: "Benchmark" };
    const times = [];
    for (let i = 0; i < 8; i++) {
      const start = performance.now(); candle.render(host, session, opts); const ms = performance.now() - start;
      if (i > 2) times.push(ms);
      candle.destroy(host);
    }
    const trade = session.trades[0];
    candle.render(host, session, { ...opts, cursor: 5 });
    const futurePaths = host.querySelectorAll(".trade-path").length;
    const visibleRows = host.querySelectorAll("tbody tr").length;
    curve.render(host, equity, { ...opts, unit: "r" });
    const rEnd = host.querySelector("figcaption").textContent;
    curve.destroy(host); host.remove();
    return { times, futurePaths, visibleRows, rEnd, flat: core.scale([2, 2], [0, 10])(2), empty: core.extent([]) };
  }, { session: fixture, equity });
  assert.equal(result.futurePaths, 0, "Future trades must not appear before entry");
  assert.equal(result.visibleRows, 6);
  assert.match(result.rEnd, /1.59 R/);
  assert.equal(result.flat, 5);
  assert.deepEqual(result.empty, [0, 1]);
  const median = [...result.times].sort((a, b) => a - b)[2];
  assert.ok(median < 16, `78-bar render median ${median.toFixed(2)} ms exceeds 16 ms`);
  console.log(`Charts: SVG, canvas, tables, focus navigation, sample split, R units and cleanup passed; 78-bar render median ${median.toFixed(2)} ms.`);
} finally { await browser.close(); }
